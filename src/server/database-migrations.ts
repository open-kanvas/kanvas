import { createHash } from 'node:crypto';
import type { PoolClient } from 'pg';
import { normalizeLegacyRecord } from './legacy-data.js';

export const DATABASE_SCHEMA_VERSION = 1;
const initial = `
  CREATE TABLE documents (
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    kind TEXT NOT NULL, id TEXT NOT NULL, session_id TEXT NOT NULL DEFAULT '',
    value TEXT NOT NULL CHECK (jsonb_typeof(value::jsonb) = 'object'), PRIMARY KEY(kind,id)
  );
  CREATE INDEX documents_session ON documents(kind,session_id,rowid);
  CREATE TABLE users (id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, display_name TEXT NOT NULL, password_hash TEXT NOT NULL);
  CREATE TABLE members (session_id TEXT NOT NULL, user_id TEXT NOT NULL REFERENCES users(id), role TEXT NOT NULL CHECK (role IN ('owner','editor','viewer')), PRIMARY KEY(session_id,user_id));
  CREATE TABLE assets (id TEXT PRIMARY KEY, bytes BYTEA NOT NULL);
  CREATE TABLE requests (session_id TEXT NOT NULL, principal TEXT NOT NULL, request_id TEXT NOT NULL, digest TEXT NOT NULL, result_id TEXT NOT NULL, kind TEXT NOT NULL, PRIMARY KEY(session_id,principal,request_id));
  CREATE TABLE request_metrics (rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, hour TEXT NOT NULL, category TEXT NOT NULL, status INTEGER NOT NULL, requests BIGINT NOT NULL, duration_ms BIGINT NOT NULL, PRIMARY KEY(hour,category,status));
`;

/** Retain JSON as source text, not JSONB, so imported decimal/source spelling
 * remains byte-for-byte intact. JSONB is used only by explicit filter queries. */
export async function migrateDatabase(client: PoolClient, schema: string): Promise<void> {
  const checksum = createHash('sha256').update(initial).digest('hex');
  await client.query('BEGIN');
  try {
    await client.query("SELECT pg_advisory_xact_lock(hashtextextended($1,0))", [`kanvas:schema:${schema}`]);
    await client.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`);
    await client.query(`SET LOCAL search_path TO "${schema}", pg_catalog`);
    await client.query('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())');
    const versions = (await client.query<{version:number;checksum:string}>('SELECT version,checksum FROM schema_migrations ORDER BY version')).rows;
    if (versions.some(v => v.version > DATABASE_SCHEMA_VERSION) || versions.some(v => v.version === 1 && v.checksum !== checksum)) throw new Error('The PostgreSQL schema is newer or differs from this release.');
    if (!versions.length) {
      await client.query(initial);
      await client.query('INSERT INTO schema_migrations(version,checksum) VALUES($1,$2)', [1,checksum]);
    }
    await preserveLegacyGuidance(client);
    await migrateVisualizerData(client);
    await client.query('COMMIT');
  } catch (error) { await client.query('ROLLBACK'); throw error; }
}

/** Data-only release migration has its own ledger: the unchanged schema remains
 * compatible with 0.19.0, which deliberately rejects newer structural versions.
 * Called within the same transaction and schema advisory lock as schema migrations. */
export async function migrateVisualizerData(client: PoolClient): Promise<void> {
  const version = 1;
  await client.query('CREATE TABLE IF NOT EXISTS data_migrations (version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())');
  const applied = (await client.query<{checksum:string}>('SELECT checksum FROM data_migrations WHERE version=$1', [version])).rows[0];
  if (applied) {
    // Checksum is a fixed contract identifier, independent of build formatting.
    if (applied.checksum !== DATA_MIGRATION_CHECKSUM) throw new Error('Data migration differs from this release.');
    return;
  }
  await client.query("DELETE FROM documents WHERE kind IN ('game','game-receipt','demo','demo-receipt')");
  // Retired game invitations are revoked, not converted into a different invitation.
  await client.query("UPDATE documents SET value=(value::jsonb - 'gameId' || jsonb_build_object('revokedAt', to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')))::text WHERE kind='invitation' AND value::jsonb ? 'gameId'");
  const rows = (await client.query<{kind:string;id:string;value:string}>("SELECT kind,id,value FROM documents WHERE kind IN ('session','preferences','session-context','group','display','display-history','view-pin','deck','update') ORDER BY rowid")).rows;
  for (const row of rows) {
    const parsed = JSON.parse(row.value), before = JSON.stringify(parsed);
    const normalized = JSON.stringify(normalizeLegacyRecord(row.kind, parsed));
    // Do not rewrite unaffected sources (including their original JSON spelling).
    if (before !== normalized) await client.query('UPDATE documents SET value=$1 WHERE kind=$2 AND id=$3', [normalized,row.kind,row.id]);
  }
  await client.query('INSERT INTO data_migrations(version,checksum) VALUES($1,$2)', [version, DATA_MIGRATION_CHECKSUM]);
}
const DATA_MIGRATION_CHECKSUM = createHash('sha256').update('kanvas-0.20.0-visualizer-data-v1').digest('hex');

